(() => {
  // mengambil elemen template dan wadah dari HTML
  const template = document.getElementById("template");
  const daftarKartu = document.getElementById("daftar-kartu");

  if (daftarKartu && template) {
    dataArtikel.forEach((artikel) => {
      // membuat salinan template
      const kartu = template.content
        .cloneNode(true)
        .querySelector(".artikel-card");

      // memberi id unik pada setiap kartu
      kartu.id = `artikel-${artikel.id}`;
      kartu.dataset.id = artikel.id;

      // mengisi gambar
      const img = kartu.querySelector(".artikel-gambar img");
      img.src = artikel.gambar;
      img.alt = artikel.judul;

      // mengisi data teks
      kartu.querySelector(".artikel-kategori").textContent = artikel.kategori;
      kartu.querySelector(".artikel-waktu").textContent = artikel.waktuBaca;
      kartu.querySelector(".artikel-title").textContent = artikel.judul;
      kartu.querySelector(".artikel-excerpt").textContent = artikel.deskripsi;

      // link "Baca Selengkapnya" menuju halaman detail berita
      kartu.querySelector(".artikel-link").href =
        `detail-berita.html?id=${artikel.id}`;

      // menambahkan kartu ke daftar
      daftarKartu.appendChild(kartu);
    });
  }

  const ikonKategori = {
    Nutrisi: "fa-leaf",
    Kebugaran: "fa-person-running",
    "Pola Tidur": "fa-moon",
  };

  function tampilkanArtikelTerkait(idAktif) {
    const wadah = document.getElementById("artikel-terkait");
    if (!wadah) return;

    wadah.replaceChildren();

    dataArtikel
      .filter((artikel) => artikel.id !== idAktif)
      .forEach((artikel) => {
        const kartu = document.createElement("div");
        kartu.className = "kartu";

        const gambar = document.createElement("img");
        gambar.src = artikel.gambar;
        gambar.alt = artikel.judul;

        const isi = document.createElement("div");
        isi.className = "kartu-isi";

        const info = document.createElement("p");
        info.className = "kartu-info";

        const ikon = document.createElement("i");
        ikon.className = `fa-solid ${
          ikonKategori[artikel.kategori] || "fa-leaf"
        }`;

        info.append(
          ikon,
          document.createTextNode(
            ` ${artikel.kategori} ${artikel.waktuBaca.replace(" baca", "")}`,
          ),
        );

        const judul = document.createElement("h3");
        judul.textContent = artikel.judul;

        const link = document.createElement("a");
        link.className = "kartu-link";
        link.href = `detail-berita.html?id=${artikel.id}`;

        const ikonLink = document.createElement("i");
        ikonLink.className = "fa-solid fa-arrow-right";
        link.append("Baca Artikel Ini ", ikonLink);

        isi.append(info, judul, link);
        kartu.append(gambar, isi);
        wadah.appendChild(kartu);
      });
  }

  // menampilkan detail artikel di detail-berita.html
  const detailBerita = document.getElementById("detail-berita");

  if (detailBerita) {
    const parameter = new URLSearchParams(window.location.search);
    const bagianTerkait = document.getElementById("bagian-terkait");
    const dariBerita = parameter.get("jenis") === "berita";

    // jika dibuka dari daftar berita, biarkan script.js yang mengisi detail
    if (dariBerita) {
      if (bagianTerkait) bagianTerkait.style.display = "none";
      return;
    }

    const idArtikel = parseInt(parameter.get("id"));
    const artikel = dataArtikel.find((item) => item.id === idArtikel);

    if (!artikel) {
      if (bagianTerkait) bagianTerkait.style.display = "none";
      return;
    }

    const gambar = document.getElementById("gambar-berita");
    gambar.src = artikel.gambar;
    gambar.alt = artikel.judul;
    gambar.style.display = "block";

    const info = document.getElementById("info-berita");
    info.style.display = "flex";

    document.getElementById("kategori-berita").textContent = artikel.kategori;
    document.getElementById("waktu-berita").textContent = artikel.waktuBaca;
    document.getElementById("tanggal-berita").textContent = artikel.tanggal;
    document.getElementById("judul-berita").textContent = artikel.judul;
    document.getElementById("deskripsi-berita").textContent = artikel.pembuka;

    const isiBerita = document.getElementById("isi-berita");
    isiBerita.replaceChildren();

    artikel.poin.forEach((poin) => {
      const kotakPoin = document.createElement("div");
      kotakPoin.className = "poin";

      const judulPoin = document.createElement("h2");
      judulPoin.textContent = poin.judul;

      const isiPoin = document.createElement("p");
      isiPoin.textContent = poin.isi;

      kotakPoin.append(judulPoin, isiPoin);
      isiBerita.appendChild(kotakPoin);
    });

    tampilkanArtikelTerkait(artikel.id);
    document.title = `${artikel.judul} - Wellora`;
    detailBerita.hidden = false;
  }
})();
